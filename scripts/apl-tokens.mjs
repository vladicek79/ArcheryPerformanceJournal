// Generates public/css/apl-tokens.css from the APL design system's tokens.json (design/apl/) and
// the app's own additions (design/apl/tokens.app.json). Run: npm run tokens
// The token names are kept as they are in the design system: --accent, --surface, --space-5, ...
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));

export const OUT = fileURLToPath(new URL('public/css/apl-tokens.css', root));

const FONT_WEIGHTS = [400, 500, 600, 700];
// Inter, self-hosted (the CSP allows no external stylesheets, and the app works offline)
const SUBSETS = [
  [
    'latin-ext',
    'U+0100-02AF, U+0304, U+0308, U+0329, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF',
  ],
  [
    'latin',
    'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  ],
];

export function buildTokensCss(
  tokens = read('design/apl/tokens.json'),
  local = read('design/apl/tokens.app.json'),
) {
  const lines = [];
  const decl = (name, value) => lines.push(`  --${name}: ${value};`);
  const fonts = [];
  for (const w of FONT_WEIGHTS)
    for (const [subset, range] of SUBSETS)
      fonts.push(
        `@font-face {\n  font-family: Inter;\n  font-style: normal;\n  font-weight: ${w};\n  font-display: swap;\n  src: url('../fonts/inter-${subset}-${w}-normal.woff2') format('woff2');\n  unicode-range: ${range};\n}`,
      );

  // A colour is one value for both themes, or a {dark, light} pair. Dark is the default.
  const themed = [];
  const colour = (t) => {
    if (typeof t.value === 'string') return decl(t.name, t.value);
    decl(t.name, t.value.dark);
    themed.push(t);
  };
  lines.push('  /* colour (dark, the default theme) */');
  for (const t of tokens.color.tokens) colour(t);
  lines.push('  /* app additions (design/apl/tokens.app.json) */');
  for (const t of local.color) colour(t);
  lines.push('  /* type */');
  for (const [name, family] of Object.entries(tokens.type.families)) decl(`font-${name}`, family);
  for (const group of tokens.type.groups)
    for (const st of group.styles) {
      // shorthand for `font:`, plus the tracking where the style has one (label)
      decl(`type-${st.name}`, `${st.fontWeight} ${st.fontSize}/${st.lineHeight} var(--font-${group.family})`);
      if (st.letterSpacing) decl(`type-${st.name}-tracking`, st.letterSpacing);
    }
  lines.push('  /* spacing */');
  for (const t of tokens.spacing.tokens) decl(t.name, t.value);
  lines.push('  /* radius */');
  for (const t of tokens.radius.tokens) decl(t.name, t.value);

  const light = `${themed.map((t) => `  --${t.name}: ${t.value.light};`).join('\n')}\n  color-scheme: light;`;
  const indent = (block) => block.replace(/^/gm, '  ');

  return (
    [
      '/* APL design tokens. GENERATED by scripts/apl-tokens.mjs from design/apl/tokens.json — do not edit by hand. */',
      ...fonts,
      `:root {\n${lines.join('\n')}\n  color-scheme: dark;\n}`,
      `/* light theme: chosen in Settings (data-theme='light' on <html>) */\n:root[data-theme='light'] {\n${light}\n}`,
      `/* …or the device is set to light and Settings says System (no data-theme) */\n@media (prefers-color-scheme: light) {\n  :root:not([data-theme]) {\n${indent(light)}\n  }\n}`,
    ].join('\n\n') + '\n'
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, buildTokensCss());
  console.log(`wrote ${OUT}`);
}
